def get_price_message(item_type: str) -> str:
    """Получить сообщение с ценами"""
    price = PRICES.get(item_type, 0)
    all_prices = "\n".join([f"• {item} — от {price} ₽" for item, price in PRICES.items()])
    return f"""Ориентировочная стоимость перетяжки для таких изделий в Перетяжкофф:
{all_prices}

Точную стоимость мастер назовёт после оценки ваших фото и подбора ткани."""

